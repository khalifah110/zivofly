/**
 * Helper to map Supabase 'profiles' row + auth metadata to frontend User model
 */
export function mapSupabaseProfileToUser(row: any, authUser?: any, fallbackEmail?: string): User {
  const email = row?.email || authUser?.email || fallbackEmail || '';
  const meta = authUser?.user_metadata || {};
  const resolvedName =
    row?.full_name ||
    meta?.full_name ||
    meta?.name ||
    email.split('@')[0] ||
    'User';
  const rawBusinessName = (row?.business_name ?? meta?.business_name ?? '').trim();
  const isAutoGeneratedBusinessName =
    rawBusinessName === 'My Business' ||
    (rawBusinessName && rawBusinessName.toLowerCase() === resolvedName.trim().toLowerCase());

  return {
    id: row?.id || authUser?.id || '',
    name: resolvedName,
    email,
    businessName: isAutoGeneratedBusinessName ? '' : rawBusinessName,
    avatarUrl: row?.avatar_url || meta?.avatar_url || meta?.picture || undefined,
  };
}

export function normalizeWorkspaceRole(
  rawRole?: string | null,
  isOwner = false
): WorkspaceRole {
  if (isOwner) return 'owner';
  const normalized = typeof rawRole === 'string' ? rawRole.trim().toLowerCase() : '';
  if (normalized === 'owner') return 'owner';
  if (normalized === 'admin') return 'admin';
  return 'member';
}

export function cleanBusinessName(rawBiz?: string | null, fullName?: string | null): string {
  const trimmed = typeof rawBiz === 'string' ? rawBiz.trim() : '';
  if (!trimmed) return '';
  if (
    trimmed === 'My Business' ||
    (fullName && trimmed.toLowerCase() === fullName.trim().toLowerCase())
  ) {
    return '';
  }
  return trimmed;
}

function isAutoGeneratedWorkspaceName(
  wsName?: string | null,
  ownerFullName?: string | null
): boolean {
  const trimmed = typeof wsName === 'string' ? wsName.trim() : '';
  if (!trimmed) return true;
  if (
    trimmed === 'My Workspace' ||
    trimmed === 'Team Workspace' ||
    trimmed === 'Shared Workspace' ||
    trimmed === 'Business Workspace' ||
    trimmed === 'My Business' ||
    /'s workspace$/i.test(trimmed)
  ) {
    return true;
  }
  if (ownerFullName && trimmed.toLowerCase() === ownerFullName.trim().toLowerCase()) {
    return true;
  }
  return false;
}

export function getStoredActiveWorkspaceId(userId: string): string | null {
  if (!userId || typeof window === 'undefined') return null;
  try {
    const val = window.localStorage.getItem(`${ACTIVE_WORKSPACE_STORAGE_PREFIX}${userId}`);
    return val && isValidUuid(val) ? val.trim() : null;
  } catch {
    return null;
  }
}

export function saveJoinedWorkspaceNameHint(workspaceId: string, name: string): void {
  if (!workspaceId || !name || typeof window === 'undefined') return;
  try {
    const raw = window.localStorage.getItem(JOINED_WORKSPACE_NAMES_KEY);
    const map: Record<string, string> = raw ? JSON.parse(raw) : {};
    map[workspaceId] = name;
    window.localStorage.setItem(JOINED_WORKSPACE_NAMES_KEY, JSON.stringify(map));
  } catch {
    // ignore storage failures
  }
}

function getJoinedWorkspaceNameHint(workspaceId: string): string | null {
  if (!workspaceId || typeof window === 'undefined') return null;
  try {
    const raw = window.localStorage.getItem(JOINED_WORKSPACE_NAMES_KEY);
    if (!raw) return null;
    const map = JSON.parse(raw);
    return typeof map?.[workspaceId] === 'string' && map[workspaceId].trim()
      ? map[workspaceId].trim()
      : null;
  } catch {
    return null;
  }
}

export function setActiveWorkspaceId(
  userId: string,
  workspaceId: string,
  workspaceName?: string
): void {
  if (!userId || !workspaceId) return;
  workspaceCache.set(userId, workspaceId);
  if (typeof window !== 'undefined') {
    try {
      window.localStorage.setItem(`${ACTIVE_WORKSPACE_STORAGE_PREFIX}${userId}`, workspaceId);
    } catch {
      // ignore storage failures
    }
  }
  if (workspaceName) {
    saveJoinedWorkspaceNameHint(workspaceId, workspaceName);
  }
}

export function clearActiveWorkspaceCache(userId?: string): void {
  if (userId) {
    workspaceCache.delete(userId);
    if (typeof window !== 'undefined') {
      try {
        window.localStorage.removeItem(`${ACTIVE_WORKSPACE_STORAGE_PREFIX}${userId}`);
      } catch {
        // ignore
      }
    }
  } else {
    workspaceCache.clear();
  }
}

/**
 * Verify if `candidateWorkspaceId` belongs to `userId` (either owned or in `workspace_members`).
 */
async function userHasWorkspaceAccess(
  userId: string,
  candidateWorkspaceId: string
): Promise<boolean> {
  if (!supabase || !isValidUuid(candidateWorkspaceId)) return false;

  const { data: owned } = await supabase
    .from('workspaces')
    .select('id')
    .eq('id', candidateWorkspaceId)
    .eq('owner_user_id', userId)
    .maybeSingle();
  if (owned?.id) return true;

  const { data: member } = await supabase
    .from('workspace_members')
    .select('workspace_id')
    .eq('workspace_id', candidateWorkspaceId)
    .eq('user_id', userId)
    .maybeSingle();
  return Boolean(member?.workspace_id);
}

/**
 * Returns all workspaces the signed-in user owns or has joined via `workspace_members`.
 */
export async function getUserWorkspaceMemberships(
  userId: string
): Promise<WorkspaceMembership[]> {
  if (!supabase || !userId) return [];

  const byId = new Map<string, WorkspaceMembership>();

  try {
    const [{ data: ownedRows }, { data: memberRows }] = await Promise.all([
      supabase
        .from('workspaces')
        .select('id, name, owner_user_id, status')
        .eq('owner_user_id', userId)
        .order('created_at', { ascending: true }),
      supabase
        .from('workspace_members')
        .select('workspace_id, member_role')
        .eq('user_id', userId),
    ]);

    const rawOwnedList = ownedRows || [];
    const memberIdsToLookup: string[] = [];
    const roleByWsId = new Map<string, WorkspaceRole>();
    const ownedWsIdSet = new Set<string>();

    for (const ws of rawOwnedList) {
      if (ws?.id) ownedWsIdSet.add(ws.id);
    }

    for (const m of memberRows || []) {
      if (!m?.workspace_id) continue;
      const role = normalizeWorkspaceRole(m.member_role, false);
      roleByWsId.set(m.workspace_id, role);
      if (!ownedWsIdSet.has(m.workspace_id)) {
        memberIdsToLookup.push(m.workspace_id);
      }
    }

    let joinedWsRows: any[] = [];
    if (memberIdsToLookup.length > 0) {
      const { data } = await supabase
        .from('workspaces')
        .select('id, name, owner_user_id, status')
        .in('id', memberIdsToLookup);
      joinedWsRows = data || [];
    }

    const ownerIdSet = new Set<string>();
    for (const ws of rawOwnedList) {
      if (ws?.owner_user_id) ownerIdSet.add(ws.owner_user_id);
    }
    for (const row of joinedWsRows) {
      if (row?.owner_user_id) ownerIdSet.add(row.owner_user_id);
    }

    const ownerProfileMap = new Map<string, { business_name?: string; full_name?: string }>();
    if (ownerIdSet.size > 0) {
      try {
        const { data: profileRows } = await supabase
          .from('profiles')
          .select('id, business_name, full_name')
          .in('id', Array.from(ownerIdSet));
        for (const p of profileRows || []) {
          if (p?.id) ownerProfileMap.set(p.id, p);
        }
      } catch {
        // Ignore if RLS restricts reading owner profiles
      }
    }

    const resolveWorkspaceName = (
      rawName: string | null | undefined,
      ownerId: string | null | undefined,
      role: WorkspaceRole,
      wsId: string
    ): string => {
      const ownerProf = ownerId ? ownerProfileMap.get(ownerId) : undefined;
      const ownerBiz = cleanBusinessName(ownerProf?.business_name, ownerProf?.full_name);
      const trimmedRaw = typeof rawName === 'string' ? rawName.trim() : '';

      if (trimmedRaw && !isAutoGeneratedWorkspaceName(trimmedRaw, ownerProf?.full_name)) {
        return trimmedRaw;
      }
      if (ownerBiz) {
        return ownerBiz;
      }
      const hint = getJoinedWorkspaceNameHint(wsId);
      if (hint && !isAutoGeneratedWorkspaceName(hint, ownerProf?.full_name)) {
        return hint;
      }
      return role === 'owner' ? 'My Workspace' : 'Business Workspace';
    };

    for (const ws of rawOwnedList) {
      if (!ws?.id) continue;
      byId.set(ws.id, {
        id: ws.id,
        name: resolveWorkspaceName(ws.name, ws.owner_user_id || userId, 'owner', ws.id),
        role: 'owner',
        ownerUserId: ws.owner_user_id,
        status: ws.status || 'active',
      });
    }

    if (memberIdsToLookup.length > 0) {
      const wsRowMap = new Map<string, any>();
      for (const row of joinedWsRows) {
        if (row?.id) wsRowMap.set(row.id, row);
      }

      for (const wsId of memberIdsToLookup) {
        const row = wsRowMap.get(wsId);
        const isOwner = row?.owner_user_id === userId;
        const role = normalizeWorkspaceRole(roleByWsId.get(wsId), isOwner);

        byId.set(wsId, {
          id: wsId,
          name: resolveWorkspaceName(row?.name, row?.owner_user_id, role, wsId),
          role,
          ownerUserId: row?.owner_user_id,
          status: row?.status || 'active',
        });
      }
    }
  } catch (err) {
    console.warn('[Zivofly] Failed to load workspace memberships:', err);
  }

  if (byId.size === 0) {
    try {
      const fallbackWsId = await getOrCreateUserWorkspace(userId);
      if (fallbackWsId) {
        const { data: wsRow } = await supabase
          .from('workspaces')
          .select('id, name, owner_user_id, status')
          .eq('id', fallbackWsId)
          .maybeSingle();

        const role: WorkspaceRole =
          wsRow?.owner_user_id && wsRow.owner_user_id !== userId ? 'member' : 'owner';
        const rawWsName = typeof wsRow?.name === 'string' ? wsRow.name.trim() : '';
        const cleanWsName =
          rawWsName && !isAutoGeneratedWorkspaceName(rawWsName)
            ? rawWsName
            : role === 'owner'
            ? 'My Workspace'
            : 'Business Workspace';

        byId.set(fallbackWsId, {
          id: fallbackWsId,
          name: cleanWsName,
          role,
          ownerUserId: wsRow?.owner_user_id || userId,
          status: wsRow?.status || 'active',
        });
      }
    } catch (e) {
      console.warn('[Zivofly] Fallback workspace creation warning:', e);
    }
  }

  // Sort owned workspaces first, then joined workspaces
  return Array.from(byId.values()).sort((a, b) => {
    if (a.role === 'owner' && b.role !== 'owner') return -1;
    if (a.role !== 'owner' && b.role === 'owner') return 1;
    return a.name.localeCompare(b.name);
  });
}

/**
 * Ensure the authenticated user has a row in `profiles` and a workspace in `workspaces` + `workspace_members`.
 * Respects the user's selected active workspace ID if valid.
 * Returns the active workspace UUID for this user.
 */
export async function getOrCreateUserWorkspace(
  userId: string,
  userEmail?: string,
  userName?: string,
  businessName?: string
): Promise<string> {
  if (!supabase) throw new Error('Supabase client is not configured.');

  const cached = workspaceCache.get(userId);
  if (cached) return cached;

  // 0. Check persisted active workspace selection
  const storedActive = getStoredActiveWorkspaceId(userId);
  if (storedActive) {
    const hasAccess = await userHasWorkspaceAccess(userId, storedActive);
    if (hasAccess) {
      workspaceCache.set(userId, storedActive);
      return storedActive;
    }
  }

  // 1. Check workspaces owned by this user
  const { data: ownedWs } = await supabase
    .from('workspaces')
    .select('id')
    .eq('owner_user_id', userId)
    .order('created_at', { ascending: true })
    .limit(1)
    .maybeSingle();

  if (ownedWs?.id) {
    setActiveWorkspaceId(userId, ownedWs.id);
    return ownedWs.id;
  }

  // 2. Check workspace_members for this user
  const { data: memberWs } = await supabase
    .from('workspace_members')
    .select('workspace_id')
    .eq('user_id', userId)
    .limit(1)
    .maybeSingle();

  if (memberWs?.workspace_id) {
    setActiveWorkspaceId(userId, memberWs.workspace_id);
    return memberWs.workspace_id;
  }

  // 3. Ensure profile exists before creating workspace (in case FK references profiles)
  try {
    const { data: existingProfile } = await supabase
      .from('profiles')
      .select('id')
      .eq('id', userId)
      .maybeSingle();

    if (!existingProfile) {
      await supabase.from('profiles').upsert(
        {
          id: userId,
          email: userEmail || '',
          full_name: userName || userEmail?.split('@')[0] || 'User',
          business_name: businessName || '',
          updated_at: new Date().toISOString(),
        },
        { onConflict: 'id' }
      );
    }
  } catch (e) {
    console.warn('[Zivofly] Profile ensure warning:', e);
  }

  // 4. Create a new workspace for this real user
  const cleanedInitialBiz = cleanBusinessName(businessName, userName);
  const wsName = cleanedInitialBiz || 'My Workspace';
  const { data: createdWs, error: wsError } = await supabase
    .from('workspaces')
    .insert({
      owner_user_id: userId,
      name: wsName,
      status: 'active',
    })
    .select('id')
    .single();

  if (wsError || !createdWs?.id) {
    throw wsError || new Error('Failed to provision user workspace in Supabase');
  }

  // 5. Link user in workspace_members
  try {
    await supabase.from('workspace_members').insert({
      workspace_id: createdWs.id,
      user_id: userId,
      member_role: 'owner',
    });
  } catch (e) {
    console.warn('[Zivofly] workspace_members insert warning:', e);
  }

  workspaceCache.set(userId, createdWs.id);
  return createdWs.id;
}

/**
 * Helper to map a single Supabase 'knowledge_documents' row to frontend KnowledgeDocument model
 */
export function mapSupabaseKnowledgeDocToFrontend(d: any): KnowledgeDocument {
  const rawContent =
    typeof d.content_text === 'string' && d.content_text.length > 0
      ? d.content_text
      : d.metadata?.content || '';
  const byteSize =
    typeof d.file_size_bytes === 'number'
      ? d.file_size_bytes
      : new TextEncoder().encode(rawContent).length;
  const formattedSize =
    d.metadata?.fileSize ||
    `${Math.max(1, Math.round(byteSize / 1024))} KB`;

  const sourceType = d.source_type || 'text';
  const docType: KnowledgeDocument['type'] =
    sourceType === 'file' || d.mime_type === 'application/pdf' || d.metadata?.type === 'pdf'
      ? 'pdf'
      : sourceType === 'faq'
      ? 'faq'
      : sourceType === 'meta_bio'
      ? 'social_bio'
      : 'text';

  const rawChunkCount = typeof d.chunk_count === 'number' ? d.chunk_count : 0;
  // A document must only be shown as 'ready' when its chunks and embeddings have been saved (chunk_count > 0)
  const effectiveStatus: KnowledgeDocument['status'] =
    d.status === 'ready' && rawChunkCount > 0
      ? 'ready'
      : d.status === 'ready' && rawChunkCount === 0
      ? 'queued'
      : d.status || 'queued';

  return {
    id: d.id,
    workspaceId: d.workspace_id,
    agentId: d.agent_id,
    name: d.title || 'Document',
    type: docType,
    sourceType,
    content: rawContent,
    mimeType: d.mime_type || 'text/plain',
    fileSizeBytes: byteSize,
    chunkCount: rawChunkCount,
    status: effectiveStatus,
    errorMessage: d.error_message || null,
    createdAt: d.created_at || new Date().toISOString(),
    updatedAt: d.updated_at || d.created_at || new Date().toISOString(),
    fileSize: formattedSize,
  };
}

/**
 * Helper to map Supabase 'agents' row + knowledge_documents rows to frontend Agent model
 */
export function mapSupabaseAgentToFrontend(row: any, docRows: any[] = [], userId = ''): Agent {
  const configDoc = docRows.find((d) => d.title === CONFIG_DOC_TITLE);
  const ext = configDoc?.metadata || {};

  const knowledgeDocs: KnowledgeDocument[] = docRows
    .filter((d) => d.title !== CONFIG_DOC_TITLE && d.status !== 'deleted')
    .map((d) => mapSupabaseKnowledgeDocToFrontend(d));

  const activeDays = Array.isArray(row.active_days)
    ? row.active_days
    : [0, 1, 2, 3, 4, 5, 6];

  return {
    id: row.id,
    userId: row.created_by || userId || '',
    workspaceId: row.workspace_id || undefined,
    name: row.name || 'AI Concierge',
    description: ext.shortDescription ?? row.description ?? '',
    platforms: Array.isArray(ext.platforms) ? ext.platforms : ['whatsapp', 'instagram'],
    roleAndDuties: ext.roleAndDuties ?? row.description ?? '',
    openingLine: row.greeting || ext.openingLine || '',
    tone: row.tone || '',
    status: row.status === 'paused' ? 'paused' : 'active',
    customVoice: ext.customVoice,
    humanHandoff: ext.humanHandoff,
    availability: {
      is24x7: row.always_on ?? true,
      timezone: row.timezone || 'America/New_York',
      startHour: row.active_from ? String(row.active_from).slice(0, 5) : '08:00',
      endHour: row.active_to ? String(row.active_to).slice(0, 5) : '20:00',
      activeDays,
    },
    platformConfig: ext.platformConfig || {},
    whatItRepliesTo: ext.whatItRepliesTo,
    knowledgeDocs,
    tools: ext.tools,
    createdAt: row.created_at || new Date().toISOString(),
    updatedAt: row.updated_at || new Date().toISOString(),
  };
}

